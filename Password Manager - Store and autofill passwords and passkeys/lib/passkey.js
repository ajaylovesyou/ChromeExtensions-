/**
 * Bitwarden Password Manager - Passkeys & WebAuthn Manager
 * Supports FIDO2 / WebAuthn passkey generation, secure keypair storage, and credential assertion.
 */

const BitPasskey = (function() {
  'use strict';

  // Base64URL encoding helper
  function bufferToBase64Url(buffer) {
    let binary = '';
    const bytes = new Uint8Array(buffer);
    for (let i = 0; i < bytes.byteLength; i++) {
      binary += String.fromCharCode(bytes[i]);
    }
    return btoa(binary)
      .replace(/\+/g, '-')
      .replace(/\//g, '_')
      .replace(/=/g, '');
  }

  function base64UrlToBuffer(base64url) {
    let base64 = base64url.replace(/-/g, '+').replace(/_/g, '/');
    while (base64.length % 4) {
      base64 += '=';
    }
    const binary = atob(base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    return bytes;
  }

  /**
   * Generate a cryptographic ECDSA P-256 (ES256) keypair for a new Passkey
   */
  async function generatePasskey(rpId, userName, userDisplayName = '') {
    // Generate ECDSA P-256 keypair
    const keyPair = await crypto.subtle.generateKey(
      {
        name: 'ECDSA',
        namedCurve: 'P-256'
      },
      true, // extractable so we can save to encrypted vault
      ['sign', 'verify']
    );

    // Export public key in SPKI format
    const spkiBuffer = await crypto.subtle.exportKey('spki', keyPair.publicKey);
    const publicKeyBase64 = BitCrypto.bufferToBase64(spkiBuffer);

    // Export private key in PKCS8 format
    const pkcs8Buffer = await crypto.subtle.exportKey('pkcs8', keyPair.privateKey);
    const privateKeyBase64 = BitCrypto.bufferToBase64(pkcs8Buffer);

    // Generate random 16-byte credential ID and 16-byte user handle
    const credentialIdRaw = BitCrypto.getRandomBytes(16);
    const credentialId = bufferToBase64Url(credentialIdRaw);
    const userHandle = bufferToBase64Url(BitCrypto.getRandomBytes(16));

    // Public key fingerprint (SHA-256 of SPKI)
    const fingerprintBuf = await crypto.subtle.digest('SHA-256', spkiBuffer);
    const fingerprint = BitCrypto.bufferToHex(fingerprintBuf).slice(0, 16);

    const now = new Date().toISOString();

    return {
      id: BitCrypto.generateUUID(),
      type: 'passkey',
      name: `${rpId} (${userName})`,
      rpId: rpId.toLowerCase(),
      userName: userName,
      userDisplayName: userDisplayName || userName,
      userHandle: userHandle,
      credentialId: credentialId,
      algorithm: 'ES256', // COSE algorithm identifier -7
      publicKey: publicKeyBase64,
      privateKey: privateKeyBase64,
      fingerprint: fingerprint,
      transports: ['internal', 'hybrid'],
      createdAt: now,
      lastUsed: now,
      notes: `FIDO2 Passkey generated by Bitwarden for ${rpId}`
    };
  }

  /**
   * Simulate or execute WebAuthn assertion signature
   */
  async function signChallenge(passkeyRecord, challengeBuffer) {
    if (!passkeyRecord || !passkeyRecord.privateKey) {
      throw new Error('Passkey private key missing');
    }

    const privateKeyBuf = BitCrypto.base64ToBuffer(passkeyRecord.privateKey);
    const privateKey = await crypto.subtle.importKey(
      'pkcs8',
      privateKeyBuf,
      {
        name: 'ECDSA',
        namedCurve: 'P-256'
      },
      false,
      ['sign']
    );

    const signature = await crypto.subtle.sign(
      {
        name: 'ECDSA',
        hash: { name: 'SHA-256' }
      },
      privateKey,
      challengeBuffer
    );

    return {
      credentialId: passkeyRecord.credentialId,
      signature: bufferToBase64Url(signature),
      userHandle: passkeyRecord.userHandle,
      authenticatorData: bufferToBase64Url(BitCrypto.getRandomBytes(37))
    };
  }

  /**
   * Verify signature using the passkey's public key
   */
  async function verifySignature(passkeyRecord, challengeBuffer, signatureBuffer) {
    const pubKeyBuf = BitCrypto.base64ToBuffer(passkeyRecord.publicKey);
    const publicKey = await crypto.subtle.importKey(
      'spki',
      pubKeyBuf,
      {
        name: 'ECDSA',
        namedCurve: 'P-256'
      },
      false,
      ['verify']
    );

    return await crypto.subtle.verify(
      {
        name: 'ECDSA',
        hash: { name: 'SHA-256' }
      },
      publicKey,
      signatureBuffer,
      challengeBuffer
    );
  }

  return {
    generatePasskey,
    signChallenge,
    verifySignature,
    bufferToBase64Url,
    base64UrlToBuffer
  };
})();

if (typeof globalThis !== 'undefined') {
  globalThis.BitPasskey = BitPasskey;
}
if (typeof window !== 'undefined') {
  window.BitPasskey = BitPasskey;
}
if (typeof self !== 'undefined') {
  self.BitPasskey = BitPasskey;
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = BitPasskey;
}
